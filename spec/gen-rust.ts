// spec/gen-rust.ts — 从 spec/tape.ts 生成 crates/pocket-bench/src/tape_spec.rs：
// tape 常量、头部 word 偏移、stage id、录制 op 表（op 码、布局字符串、RET 种类）。
// 生成物提交进仓库；spec/gen.test.ts 字节比对防漂移。
//
//   bun spec/gen-rust.ts            写文件
//   bun spec/gen-rust.ts --check    只比对

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { OP } from "../vendor/pocketjs/contracts/spec/spec.ts";
import { STAGES } from "./gen-c.ts";
import {
  ACTION_ITERATION,
  DRAWLIST_TAPE_HEADER,
  DRAWLIST_TAPE_MAGIC,
  MUTATION_TAPE_HEADER,
  MUTATION_TAPE_MAGIC,
  OP_ARG_LAYOUT,
  PIXEL_FORMAT,
  RECORD_HEADER,
  RECORD_KIND,
  RETURNING_OP_RET_KIND,
  RETURNING_OPS,
  RET_KIND,
  TAPE_FRAMEWORK,
  TAPE_SOURCE,
  TAPE_VERSION,
  type ArgKind,
  type HeaderField,
  type RecordedOp,
} from "./tape.ts";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const OUT_PATH = join(ROOT, "crates/pocket-bench/src/tape_spec.rs");

const LAYOUT_CHAR: Record<ArgKind, string> = { i32: "i", u32: "u", f32: "f", f64: "d", str: "s", blob: "b" };

function screaming(name: string): string {
  return name.replace(/([A-Z])/g, "_$1").toUpperCase();
}

function headerOffsets(fields: readonly HeaderField[], prefix: string, put: (l?: string) => void): void {
  let offset = 0;
  for (const f of fields) {
    if (f.kind === "u64Array") {
      put(`pub const ${prefix}_${f.name.toUpperCase()}_OFFSET: usize = ${offset}; // ${f.count} × u64`);
      break;
    }
    put(`pub const ${prefix}_${f.name.toUpperCase()}: usize = ${offset};${f.note ? ` // ${f.note}` : ""}`);
    offset += f.kind === "u32" ? 1 : 2;
  }
  put(`pub const ${prefix}_FIXED_WORDS: usize = ${offset};`);
}

export function generateRust(): string {
  const lines: string[] = [];
  const put = (l = "") => lines.push(l);
  put("// Generated by spec/gen-rust.ts from spec/tape.ts and vendor/pocketjs/contracts/spec/spec.ts.");
  put("// Do not edit: run `bun spec/gen-rust.ts` and commit the result; spec/gen.test.ts byte-compares it.");
  put("#![allow(dead_code)]");
  put();
  put(`pub const TAPE_VERSION: u32 = ${TAPE_VERSION};`);
  put(`pub const MUTATION_TAPE_MAGIC: u32 = 0x${MUTATION_TAPE_MAGIC.toString(16).toUpperCase()}; // "PKMT"`);
  put(`pub const DRAWLIST_TAPE_MAGIC: u32 = 0x${DRAWLIST_TAPE_MAGIC.toString(16).toUpperCase()}; // "PKDL"`);
  put();
  put("/// Record header word: bits 0-7 kind, bits 8-31 payload words (not counting the header).");
  put(`pub const RECORD_KIND_MASK: u32 = 0x${RECORD_HEADER.kindMask.toString(16)};`);
  put(`pub const RECORD_PAYLOAD_SHIFT: u32 = ${RECORD_HEADER.payloadShift};`);
  put(`pub const RECORD_PAYLOAD_MAX: u32 = 0x${RECORD_HEADER.payloadMaxWords.toString(16)};`);
  for (const [k, v] of Object.entries(RECORD_KIND)) put(`pub const RECORD_${k.toUpperCase()}: u32 = ${v};`);
  put();
  put("/// ACTION payload: iteration word, then the name (len + padded words).");
  for (const [k, v] of Object.entries(ACTION_ITERATION)) put(`pub const ACTION_${screaming(k)}: u32 = ${v};`);
  put();
  for (const [k, v] of Object.entries(RET_KIND)) put(`pub const RET_${screaming(k)}: u32 = ${v};`);
  put();
  for (const [k, v] of Object.entries(TAPE_SOURCE)) put(`pub const SOURCE_${screaming(k)}: u32 = ${v};`);
  for (const [k, v] of Object.entries(TAPE_FRAMEWORK)) put(`pub const FRAMEWORK_${screaming(k)}: u32 = ${v};`);
  for (const [k, v] of Object.entries(PIXEL_FORMAT)) put(`pub const PIXEL_${k.toUpperCase()}: u32 = ${v};`);
  put();
  put("/// FRAME payload words.");
  put("pub const FRAME_INDEX: usize = 0;");
  put("pub const FRAME_BUTTONS: usize = 1;");
  put("pub const FRAME_ANALOG: usize = 2;");
  put("pub const FRAME_TICKS: usize = 3;");
  put("pub const FRAME_TOUCH_WORDS: usize = 4;");
  put("pub const FRAME_FIXED_WORDS: usize = 5;");
  put();
  put("/// MutationTape header word offsets (u64 fields take two words, low first).");
  headerOffsets(MUTATION_TAPE_HEADER, "MT", put);
  put();
  put("/// DrawListTape header word offsets.");
  headerOffsets(DRAWLIST_TAPE_HEADER, "DL", put);
  put();
  put("/// Stage ids: 0-4 match POCKET_BENCH_STAGE_* in hosts/soft/pocket_runtime.h.");
  for (const [name, id] of STAGES) put(`pub const STAGE_${name}: u32 = ${id};`);
  put(`pub const STAGE_COUNT: usize = ${STAGES.length};`);
  put();
  put("/// Op codes of the recorded ops (from the spec OP table).");
  const ops = Object.keys(OP_ARG_LAYOUT) as RecordedOp[];
  for (const op of ops) put(`pub const OP_${screaming(op)}: u32 = ${OP[op]};`);
  put();
  put("/// Recorded ops: layout chars i=i32 u=u32 f=f32 d=f64 s=str b=blob.");
  put("pub struct OpSpec {");
  put("    pub op: u32,");
  put("    pub name: &'static str,");
  put("    pub layout: &'static str,");
  put("    pub ret_kind: Option<u32>,");
  put("}");
  put();
  put("#[rustfmt::skip]");
  put(`pub const OPS: [OpSpec; ${ops.length}] = [`);
  for (const op of ops) {
    const ret = (RETURNING_OPS as readonly string[]).includes(op)
      ? `Some(${RETURNING_OP_RET_KIND[op as (typeof RETURNING_OPS)[number]]})`
      : "None";
    const layout = OP_ARG_LAYOUT[op].map((k) => LAYOUT_CHAR[k]).join("");
    put(`    OpSpec { op: ${OP[op]}, name: "${op}", layout: "${layout}", ret_kind: ${ret} },`);
  }
  put("];");
  put();
  put("pub fn op_spec(op: u32) -> Option<&'static OpSpec> {");
  put("    OPS.iter().find(|s| s.op == op)");
  put("}");
  return lines.join("\n") + "\n";
}

if (import.meta.main) {
  const text = generateRust();
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, "utf8") : null;
    if (current !== text) {
      console.error(`gen-rust: ${OUT_PATH} is out of date — run \`bun spec/gen-rust.ts\``);
      process.exit(1);
    }
  } else {
    writeFileSync(OUT_PATH, text);
    console.log(`gen-rust: ${OUT_PATH}`);
  }
}
